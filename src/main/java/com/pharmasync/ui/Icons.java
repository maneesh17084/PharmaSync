package com.pharmasync.ui;

import com.formdev.flatlaf.extras.FlatSVGIcon;

import javax.imageio.ImageIO;
import javax.swing.Icon;
import javax.swing.UIManager;
import java.awt.Color;
import java.awt.Component;
import java.awt.Graphics;
import java.awt.Graphics2D;
import java.awt.Image;
import java.awt.RenderingHints;
import java.awt.image.BaseMultiResolutionImage;
import java.awt.image.BufferedImage;
import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.util.ArrayList;
import java.util.List;
import java.util.function.Supplier;

/**
 * SVG icons from resources/com/pharmasync/icons, recoloured to match the theme, and the PharmaSync logo
 * (PNG renditions in resources/com/pharmasync/brand, generated by branding/make_logo.py).
 */
public final class Icons {

    private static final String DIR = "com/pharmasync/icons/";
    private static final String BRAND = "/com/pharmasync/brand/";
    private static final int[] APP_SIZES = {16, 20, 24, 32, 40, 48, 64, 72, 96, 128, 256, 512};
    private static final int[] MARK_WIDTHS = {256, 384, 512};

    private static List<BufferedImage> appImages;
    private static Image appIcon;
    private static Image logoMark;
    private static double markAspect;

    private Icons() {
    }

    /** Icon in the normal text colour of the current theme. */
    public static FlatSVGIcon get(String name, int size) {
        return get(name, size, () -> UIManager.getColor("Label.foreground"));
    }

    /** Icon whose colour is looked up each time it is painted (so it follows theme changes). */
    public static FlatSVGIcon get(String name, int size, Supplier<Color> color) {
        FlatSVGIcon icon = new FlatSVGIcon(DIR + name + ".svg", size, size);
        icon.setColorFilter(new FlatSVGIcon.ColorFilter(c -> color.get()));
        return icon;
    }

    public static FlatSVGIcon fixed(String name, int size, Color color) {
        return get(name, size, () -> color);
    }

    /** The app icon (emblem on its rounded tile) at the given logical size. */
    public static synchronized Icon logo(int size) {
        if (appIcon == null) {
            appIcon = new BaseMultiResolutionImage(appImages().toArray(new Image[0]));
        }
        return new ImageIcon(appIcon, size, size);
    }

    /**
     * The logo with the PharmaSync wordmark and no tile (transparent background), so it blends into the dark
     * sign-in panel. Height follows the artwork's proportions.
     */
    public static synchronized Icon logoMark(int width) {
        if (logoMark == null) {
            List<BufferedImage> images = new ArrayList<>();
            for (int n : MARK_WIDTHS) {
                images.add(read("logo-mark-" + n + ".png"));
            }
            logoMark = new BaseMultiResolutionImage(images.toArray(new Image[0]));
            BufferedImage base = images.get(0);
            markAspect = (double) base.getHeight() / base.getWidth();
        }
        return new ImageIcon(logoMark, width, (int) Math.round(width * markAspect));
    }

    /** Window/taskbar icons in several sizes; the platform picks the best fit. */
    public static List<Image> windowIcons() {
        return new ArrayList<>(appImages());
    }

    private static synchronized List<BufferedImage> appImages() {
        if (appImages == null) {
            List<BufferedImage> images = new ArrayList<>();
            for (int n : APP_SIZES) {
                images.add(read("app-" + n + ".png"));
            }
            appImages = images;
        }
        return appImages;
    }

    private static BufferedImage read(String name) {
        try (InputStream in = Icons.class.getResourceAsStream(BRAND + name)) {
            if (in == null) {
                throw new IllegalStateException("Missing resource " + BRAND + name);
            }
            return ImageIO.read(in);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    /**
     * Icon drawing a multi-resolution image at a logical size; Java2D picks the rendition that matches
     * the screen scale, so the logo stays sharp on high-DPI displays.
     */
    private record ImageIcon(Image image, int width, int height) implements Icon {
        @Override
        public void paintIcon(Component c, Graphics g, int x, int y) {
            Graphics2D g2 = (Graphics2D) g.create();
            g2.setRenderingHint(RenderingHints.KEY_INTERPOLATION, RenderingHints.VALUE_INTERPOLATION_BICUBIC);
            g2.setRenderingHint(RenderingHints.KEY_RENDERING, RenderingHints.VALUE_RENDER_QUALITY);
            g2.drawImage(image, x, y, width, height, null);
            g2.dispose();
        }

        @Override
        public int getIconWidth() {
            return width;
        }

        @Override
        public int getIconHeight() {
            return height;
        }
    }
}
